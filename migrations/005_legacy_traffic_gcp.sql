-- El repositorio Go infrastructure/repositories/postgres_traffic_store.go escribe y lee
-- tres tablas PLANAS -- traffic_batches, traffic_samples, traffic_aggregates -- con SQL
-- inline, SIN pasar por prc_/fnc_ y SIN tenant_id. Ese DDL nunca estuvo versionado: las
-- tablas se asumian pre-creadas. Aqui se formaliza tal cual, para que una BD limpia levante
-- completa y el path GCP (BigQuery/Pub-Sub/Redis + estas tablas) siga funcionando sin tocar
-- el codigo.
--
-- DECISION (usuario, 2026-08-01): se CONSERVA el diseno GCP actual. NO se reescribe a
-- traffic.observation/link/live_state del modelo procedural de 001_vehitrack. Ambos mundos
-- coexisten:
--   * PG-procedural (geo/tenant/tracking/routing/offline/ops)  <- capas nuevas del roadmap
--   * GCP plano (estas tablas + BigQuery/Pub-Sub/Redis)         <- telemetria/trafico actual
-- La convergencia (telemetria derivando traffic.observation) se agenda para F6/F7, no aqui.
--
-- IMPORTANTE: estas tablas viven en `public` (nombres SIN esquema en el Go, resueltos por
-- search_path). NO colisionan con el esquema `traffic` de 001_vehitrack: esquema y tabla
-- son namespaces distintos.
-- =====================================================================================

BEGIN;

SET LOCAL client_min_messages = WARNING;

-- ─────────────────────────────────────────────────────────────────────────────────────
-- 1. LOTES
--    IngestBatch: EXISTS(SELECT 1 FROM traffic_batches WHERE batch_id = $1)
--                 INSERT INTO traffic_batches (batch_id, sample_count, duplicate)
-- ─────────────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.traffic_batches (
    batch_id     text        PRIMARY KEY,
    sample_count int         NOT NULL,
    duplicate    boolean     NOT NULL DEFAULT false,
    received_at  timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE public.traffic_batches IS
    'Path GCP heredado (Copiloto F3). Idempotencia por batch_id: reenviar un lote no duplica.';

-- ─────────────────────────────────────────────────────────────────────────────────────
-- 2. MUESTRAS
--    INSERT INTO traffic_samples (batch_id, cell, speed_kmh, sampled_at, accuracy_m, session_id)
--    RefreshAggregates lee: cell, sampled_at, speed_kmh, session_id
-- ─────────────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.traffic_samples (
    id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id   text        NOT NULL REFERENCES public.traffic_batches(batch_id) ON DELETE CASCADE,
    cell       text        NOT NULL,
    speed_kmh  numeric(6,2) NOT NULL,
    sampled_at timestamptz NOT NULL,
    accuracy_m numeric(8,2),
    session_id text        NOT NULL
);
COMMENT ON COLUMN public.traffic_samples.session_id IS
    'Identificador de sesion anonimo. device_count = COUNT(DISTINCT session_id) en el rollup.';
CREATE INDEX IF NOT EXISTS ix_traffic_samples_sampled_at ON public.traffic_samples (sampled_at);
CREATE INDEX IF NOT EXISTS ix_traffic_samples_cell        ON public.traffic_samples (cell);

-- ─────────────────────────────────────────────────────────────────────────────────────
-- 3. AGREGADOS
--    ON CONFLICT (cell, slot, corridor) DO UPDATE ...
--    AggregatesByCorridor: WHERE corridor = $1 AND slot = $2
-- ─────────────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.traffic_aggregates (
    cell             text         NOT NULL,
    slot             int          NOT NULL,
    corridor         text         NOT NULL,
    median_speed_kmh numeric(6,2),
    sample_count     int          NOT NULL DEFAULT 0,
    device_count     int          NOT NULL DEFAULT 0,
    updated_at       timestamptz  NOT NULL DEFAULT now(),
    PRIMARY KEY (cell, slot, corridor)
);
COMMENT ON TABLE public.traffic_aggregates IS
    'Rollup por (cell, slot, corridor). slot = media hora del dia (0..47). corridor = LEFT(cell,5).';
CREATE INDEX IF NOT EXISTS ix_traffic_aggregates_corridor_slot
    ON public.traffic_aggregates (corridor, slot);

COMMIT;

